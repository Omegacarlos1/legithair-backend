CREATE TABLE orders (
  id CHAR(36) NOT NULL,
  quote_id CHAR(36) NOT NULL,
  basket_id CHAR(36) NOT NULL,
  user_id CHAR(36) NULL,
  guest_tracking_token_hash CHAR(64) NULL,
  idempotency_key VARCHAR(128) NOT NULL,
  request_hash CHAR(64) NOT NULL,
  payment_method ENUM('paystack', 'cod') NOT NULL,
  status ENUM('awaiting_payment', 'awaiting_collection', 'paid', 'payment_failed', 'reservation_expired', 'cancelled', 'processing', 'shipped', 'delivered', 'returned', 'refunded') NOT NULL,
  delivery_method ENUM('delivery', 'pickup') NOT NULL,
  destination_snapshot JSON NULL,
  items_subtotal_minor BIGINT UNSIGNED NOT NULL,
  delivery_total_minor BIGINT UNSIGNED NOT NULL,
  grand_total_minor BIGINT UNSIGNED NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'NGN',
  commission_basis VARCHAR(50) NOT NULL,
  commission_rate_bps SMALLINT UNSIGNED NOT NULL,
  reservation_expires_at DATETIME(3) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_orders_quote (quote_id),
  UNIQUE KEY uq_orders_basket_key (basket_id, idempotency_key),
  KEY idx_orders_user_created (user_id, created_at),
  KEY idx_orders_expiry_status (reservation_expires_at, status),
  CONSTRAINT fk_orders_quote FOREIGN KEY (quote_id) REFERENCES checkout_quotes(id) ON DELETE RESTRICT,
  CONSTRAINT fk_orders_basket FOREIGN KEY (basket_id) REFERENCES baskets(id) ON DELETE RESTRICT,
  CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT chk_order_owner CHECK ((user_id IS NOT NULL AND guest_tracking_token_hash IS NULL) OR (user_id IS NULL AND guest_tracking_token_hash IS NOT NULL)),
  CONSTRAINT chk_order_commission_rate CHECK (commission_rate_bps <= 10000)
) ENGINE=InnoDB;

CREATE TABLE seller_suborders (
  id CHAR(36) NOT NULL,
  order_id CHAR(36) NOT NULL,
  seller_id CHAR(36) NOT NULL,
  status ENUM('pending', 'processing', 'shipped', 'delivered', 'cancelled', 'returned', 'refunded') NOT NULL DEFAULT 'pending',
  items_subtotal_minor BIGINT UNSIGNED NOT NULL,
  delivery_fee_minor BIGINT UNSIGNED NOT NULL,
  commission_minor BIGINT UNSIGNED NOT NULL,
  seller_net_minor BIGINT UNSIGNED NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_seller_suborders_order_seller (order_id, seller_id),
  KEY idx_seller_suborders_seller_status (seller_id, status),
  CONSTRAINT fk_seller_suborders_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_seller_suborders_seller FOREIGN KEY (seller_id) REFERENCES sellers(id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE order_items (
  id CHAR(36) NOT NULL,
  order_id CHAR(36) NOT NULL,
  suborder_id CHAR(36) NOT NULL,
  product_id CHAR(36) NOT NULL,
  seller_id CHAR(36) NOT NULL,
  product_name VARCHAR(180) NOT NULL,
  quantity SMALLINT UNSIGNED NOT NULL,
  unit_price_minor BIGINT UNSIGNED NOT NULL,
  line_total_minor BIGINT UNSIGNED NOT NULL,
  commission_basis VARCHAR(50) NOT NULL,
  commission_rate_bps SMALLINT UNSIGNED NOT NULL,
  commission_minor BIGINT UNSIGNED NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_order_items_order_product (order_id, product_id),
  KEY idx_order_items_suborder (suborder_id),
  KEY idx_order_items_product (product_id),
  CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_order_items_suborder FOREIGN KEY (suborder_id) REFERENCES seller_suborders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT,
  CONSTRAINT fk_order_items_seller FOREIGN KEY (seller_id) REFERENCES sellers(id) ON DELETE RESTRICT,
  CONSTRAINT chk_order_item_quantity CHECK (quantity BETWEEN 1 AND 20),
  CONSTRAINT chk_order_item_commission_rate CHECK (commission_rate_bps <= 10000)
) ENGINE=InnoDB;

CREATE TABLE inventory_reservations (
  id CHAR(36) NOT NULL,
  order_id CHAR(36) NOT NULL,
  order_item_id CHAR(36) NOT NULL,
  product_id CHAR(36) NOT NULL,
  quantity SMALLINT UNSIGNED NOT NULL,
  status ENUM('active', 'consumed', 'released') NOT NULL DEFAULT 'active',
  expires_at DATETIME(3) NOT NULL,
  released_at DATETIME(3) NULL,
  release_reason VARCHAR(50) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_inventory_reservations_order_item (order_item_id),
  KEY idx_inventory_reservations_due (status, expires_at),
  KEY idx_inventory_reservations_product (product_id, status),
  CONSTRAINT fk_inventory_reservations_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_inventory_reservations_item FOREIGN KEY (order_item_id) REFERENCES order_items(id) ON DELETE RESTRICT,
  CONSTRAINT fk_inventory_reservations_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE order_status_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  order_id CHAR(36) NOT NULL,
  from_status VARCHAR(40) NULL,
  to_status VARCHAR(40) NOT NULL,
  reason VARCHAR(100) NOT NULL,
  actor_type ENUM('system', 'customer', 'admin', 'provider') NOT NULL,
  actor_user_id CHAR(36) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_order_status_events_order (order_id, id),
  CONSTRAINT fk_order_status_events_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_order_status_events_actor FOREIGN KEY (actor_user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
